use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{ensure, Result};
use chrono::{Datelike, Days, NaiveDate};

use super::{aqua, viirs, Counts, Series, REGIONS, SCOPES};

const MODELS: [&str; 6] = ["raw", "ratio", "l1_day", "l1_week", "l1_month", "ratio_phase"];
pub(super) const POOLED_RATIO: usize = 1;
pub(super) const PHASE_RATIO: usize = 5;
const SIMPLICITY: [usize; 6] = [0, 1, 3, 3, 3, 2];
const CLOSE_WAPE: f64 = 0.01;
pub(super) const BIAS_LIMIT: f64 = 0.20;
const SCALES: [&str; 3] = ["day", "week", "month"];
pub(super) type Period = (NaiveDate, Counts);
pub(super) type Factor = [f64; 2];

fn select(wapes: [Option<f64>; 6]) -> Option<usize> {
    let best = wapes.into_iter().flatten().min_by(f64::total_cmp)?;
    wapes.into_iter().enumerate()
        .filter_map(|(m, wape)| wape.filter(|w| w - best < CLOSE_WAPE).map(|w| (m, w)))
        .min_by(|(a, wa), (b, wb)| SIMPLICITY[*a].cmp(&SIMPLICITY[*b]).then(wa.total_cmp(wb)))
        .map(|(m, _)| m)
}

pub(super) fn export(out: &Path, model: usize, factor: Factor, n: usize, counts: Counts,
                     status: &str) -> Result<()> {
    let mut writer = csv::Writer::from_path(out.join("modis_viirs_coefficients.csv"))?;
    writer.write_record(["metric", "source_platform", "reference_platform", "model",
        "training_scale", "application", "k_day", "k_night", "k_combined", "training_years",
        "excluded_region", "training_regions", "training_aqua", "training_snpp", "status"])?;
    let scale = match MODELS[model] {
        "l1_day" => "day",
        "l1_week" => "complete_utc_week",
        "l1_month" => "calendar_month",
        "ratio_phase" => "utc_detections_by_daynight",
        _ => "pooled_utc_detections",
    };
    let [day, night] = factor;
    let combined = (MODELS[model] != "ratio_phase").then_some(day);
    writer.serialize(("hotspot_count", "Aqua MODIS", "S-NPP VIIRS 375 m", MODELS[model],
        scale, "complete_utc_calendar_month_type_0_firms", day, night, combined, "2018-2019",
        REGIONS[0].name, n, aqua(counts), viirs(counts), status))?;
    writer.flush()?;

    let combined = combined.map_or_else(|| "None".into(), |k| k.to_string());
    let command = if status.ends_with("_e19") { "hotspots-e19" } else { "hotspots --freeze" };
    fs::write(out.join("constants_hotspots.py"), format!(
        "# Auto-generated by fire-prep {command}.\n\
         # Aqua MODIS hotspot counts to S-NPP VIIRS 375 m, full UTC calendar months.\n\
         K_HOTSPOTS_DAY = {day}\nK_HOTSPOTS_NIGHT = {night}\nK_HOTSPOTS_COMBINED = {combined}\n"
    ))?;
    Ok(())
}

pub(super) fn periods(series: &Series, region: usize, scope: usize, year: i32, scale: usize) -> Vec<Period> {
    let start = NaiveDate::from_ymd_opt(year, 1, 1).unwrap();
    let end = NaiveDate::from_ymd_opt(year, 12, 31).unwrap();
    let mut result = BTreeMap::<NaiveDate, Counts>::new();
    for (&(_, _, date), counts) in series.range((region, scope, start)..=(region, scope, end)) {
        let period = match scale {
            0 => date,
            1 => {
                let monday = date - Days::new(date.weekday().num_days_from_monday().into());
                if monday < start || monday + Days::new(6) > end {
                    continue;
                }
                monday
            }
            2 => date.with_day(1).unwrap(),
            _ => unreachable!(),
        };
        for (total, count) in result.entry(period).or_default().iter_mut().zip(counts) {
            *total += count;
        }
    }
    result.into_iter().collect()
}

fn sum(rows: &[Period]) -> Counts {
    let mut total = [0; 4];
    for (_, counts) in rows {
        for (a, b) in total.iter_mut().zip(counts) {
            *a += b;
        }
    }
    total
}

pub(super) fn train(series: &Series, omit: usize) -> Result<([Factor; 6], usize, Counts)> {
    let regions: Vec<_> = (0..7).filter(|&r| r != omit).collect();
    let mut support = [0; 4];
    let mut positive_phase_regions = [0; 2];
    let mut l1 = [Vec::new(), Vec::new(), Vec::new()];
    for &r in &regions {
        for (scale, ratios) in l1.iter_mut().enumerate() {
            let mut rows = periods(series, r, 0, 2018, scale);
            rows.extend(periods(series, r, 0, 2019, scale));
            let counts = sum(&rows);
            ensure!(aqua(counts) > 0 && viirs(counts) > 0, "Missing training support");
            if scale == 0 {
                for (total, c) in support.iter_mut().zip(counts) {
                    *total += c;
                }
                for (p, n) in positive_phase_regions.iter_mut().enumerate() {
                    *n += usize::from(counts[p] > 0 && counts[p + 2] > 0);
                }
            }
            for (_, c) in rows.into_iter().filter(|&(_, c)| aqua(c) > 0) {
                ratios.push((viirs(c) as f64 / aqua(c) as f64, aqua(c) as f64 / viirs(counts) as f64));
            }
        }
    }
    ensure!(regions.len() >= 5 && positive_phase_regions.iter().all(|&n| n >= 5), "Insufficient support");
    let mut factors = [[1.0; 2]; 6];
    factors[POOLED_RATIO] = [viirs(support) as f64 / aqua(support) as f64; 2];
    for (i, rows) in l1.iter_mut().enumerate() {
        rows.sort_by(|a, b| a.0.total_cmp(&b.0));
        let half = rows.iter().map(|r| r.1).sum::<f64>() / 2.0;
        let mut weight = 0.0;
        let (ratio, _) = rows.iter().find(|r| {
            weight += r.1;
            weight >= half
        }).unwrap();
        factors[i + 2] = [*ratio; 2];
    }
    factors[PHASE_RATIO] = [support[2] as f64 / support[0] as f64, support[3] as f64 / support[1] as f64];
    Ok((factors, regions.len(), support))
}

fn predict(c: Counts, f: Factor) -> f64 {
    c[0] as f64 * f[0] + c[1] as f64 * f[1]
}

fn ratio(n: f64, d: u64) -> Option<f64> {
    (d > 0).then(|| n / d as f64)
}

fn ranks(values: &[f64]) -> Vec<f64> {
    let mut order: Vec<_> = (0..values.len()).collect();
    order.sort_by(|&a, &b| values[a].total_cmp(&values[b]));
    let mut result = vec![0.0; values.len()];
    let mut i = 0;
    for ties in order.chunk_by(|&a, &b| values[a] == values[b]) {
        let mean = i as f64 + (ties.len() - 1) as f64 / 2.0;
        for &j in ties {
            result[j] = mean;
        }
        i += ties.len();
    }
    result
}

fn spearman(a: &[f64], b: &[f64]) -> Option<f64> {
    let mean = (a.len() - 1) as f64 / 2.0;
    let mut cov = 0.0;
    let mut va = 0.0;
    let mut vb = 0.0;
    for (x, y) in ranks(a).into_iter().zip(ranks(b)) {
        cov += (x - mean) * (y - mean);
        va += (x - mean).powi(2);
        vb += (y - mean).powi(2);
    }
    (va * vb > 0.0).then(|| cov / (va * vb).sqrt())
}

fn top3(values: &[f64]) -> Vec<usize> {
    let mut order: Vec<_> = (0..values.len()).collect();
    order.sort_by(|&a, &b| values[b].total_cmp(&values[a]));
    order.truncate(3);
    order
}

fn paired_interval(rows: &[Period], f: Factor) -> (Option<f64>, Option<f64>) {
    let quarters: Vec<_> = rows.chunks_exact(3).map(|months| {
        let mut diff = 0.0;
        let mut obs = 0;
        for &(_, c) in months {
            let v = viirs(c) as f64;
            diff += (predict(c, f) - v).abs() - (aqua(c) as f64 - v).abs();
            obs += viirs(c);
        }
        (diff, obs)
    }).collect();
    let mut draws = Vec::new();
    for draw in 0..256 {
        let mut diff = 0.0;
        let mut obs = 0;
        for shift in [0, 2, 4, 6] {
            let (d, n) = quarters[(draw >> shift) & 3];
            diff += d;
            obs += n;
        }
        draws.extend(ratio(diff, obs));
    }
    draws.sort_by(f64::total_cmp);
    if draws.is_empty() { return (None, None) }
    let last = (draws.len() - 1) as f64;
    (Some(draws[(0.025 * last).floor() as usize]), Some(draws[(0.975 * last).ceil() as usize]))
}

pub(super) fn evaluate(series: &Series, domains: &[(usize, i32)], out: &Path, freeze: bool) -> Result<()> {
    let mut factors = csv::Writer::from_path(out.join("research_coefficients.csv"))?;
    factors.write_record(["excluded_region", "model", "training_years", "reference", "metric", "k_day",
        "k_night", "training_regions", "aqua_day", "aqua_night", "snpp_day", "snpp_night", "status"])?;
    let mut folds = Vec::new();
    let mut western_support = None;
    for (r, region) in REGIONS.iter().enumerate() {
        let (candidates, n, c) = train(series, r)?;
        if r == 0 {
            western_support = Some((n, c));
        }
        for (model, f) in MODELS.iter().zip(candidates) {
            factors.serialize((region.name, model, "2018–2019", "S-NPP", "hotspot_count",
                f[0], f[1], n, c[0], c[1], c[2], c[3], "research"))?;
        }
        folds.push(candidates);
    }
    let mut metrics = csv::Writer::from_path(out.join("validation.csv"))?;
    metrics.write_record(["region", "year", "scope", "scale", "model", "periods", "aqua", "snpp",
        "mae", "wape", "bias_count", "relative_bias", "snpp_only_periods", "snpp_in_snpp_only_periods"])?;
    let mut peaks = csv::Writer::from_path(out.join("monthly_peaks.csv"))?;
    peaks.write_record(["region", "year", "scope", "model", "spearman", "top3_overlap",
        "delta_wape_block_p025", "delta_wape_block_p975"])?;
    let mut monthly = csv::Writer::from_path(out.join("monthly_predictions.csv"))?;
    monthly.write_record(["region", "scope", "month_utc", "model", "aqua", "snpp", "estimate"])?;
    let mut control = [[(0.0, 0.0); 9]; 6];
    let mut chosen = None;
    let mut western_years = 0;
    let mut western_wins = 0;
    let mut western_bias_passes = 0;
    // The discovery loop finishes and freezes the family before later years are scored.
    for fresh in [false, true] {
        for &(r, year) in domains.iter().filter(|&&(_, y)| if fresh { y > 2020 } else { y == 2020 }) {
            let name = REGIONS[r].name;
            for (scope, label) in SCOPES.iter().enumerate() {
                for (scale, scale_name) in SCALES.iter().enumerate() {
                    let rows = periods(series, r, scope, year, scale);
                    let start = NaiveDate::from_ymd_opt(year, 1, 1).unwrap();
                    let days = NaiveDate::from_ymd_opt(year, 12, 31).unwrap()
                        .signed_duration_since(start).num_days() as usize + 1;
                    let first_week_offset = (7 - start.weekday().num_days_from_monday() as usize) % 7;
                    let expected = [days, (days - first_week_offset) / 7, 12][scale];
                    ensure!(rows.len() == expected, "Incomplete control periods");
                    let counts = sum(&rows);
                    let missing: Vec<_> = rows.iter().filter(|(_, c)| aqua(*c) == 0 && viirs(*c) > 0).collect();
                    let missing_v: u64 = missing.iter().map(|(_, c)| viirs(*c)).sum();
                    let mut raw_wape = None;
                    for (m, model) in MODELS.iter().enumerate() {
                        if fresh && m != 0 && Some(m) != chosen {
                            continue;
                        }
                        let f = folds[r][m];
                        let mut abs = 0.0;
                        let mut bias = 0.0;
                        let mut estimate = Vec::new();
                        let mut observed = Vec::new();
                        for &(date, c) in &rows {
                            let value = predict(c, f);
                            let error = value - viirs(c) as f64;
                            abs += error.abs();
                            bias += error;
                            if scale == 2 {
                                monthly.serialize((name, label, date.to_string(), model, aqua(c), viirs(c), value))?;
                                estimate.push(value);
                                observed.push(viirs(c) as f64);
                            }
                        }
                        let wape = ratio(abs, viirs(counts));
                        let relative = ratio(bias, viirs(counts));
                        metrics.serialize((name, year, label, scale_name, model, rows.len(),
                            aqua(counts), viirs(counts), abs / rows.len() as f64, wape, bias,
                            relative, missing.len(), missing_v))?;
                        if scale == 2 {
                            let overlap = if estimate.iter().all(|v| *v == 0.0)
                                || observed.iter().all(|v| *v == 0.0) { None } else {
                                let actual = top3(&observed);
                                Some(top3(&estimate).iter().filter(|i| actual.contains(i)).count())
                            };
                            let ci = paired_interval(&rows, f);
                            peaks.serialize((name, year, label, model, spearman(&estimate, &observed),
                                             overlap, ci.0, ci.1))?;
                            if !fresh && scope == 0 {
                                control[m][r] = (wape.unwrap(), relative.unwrap());
                            }
                            if fresh && r == 0 && scope == 0 {
                                if m == 0 {
                                    raw_wape = wape;
                                } else {
                                    let wape = wape.ok_or_else(|| anyhow::anyhow!("Undefined western WAPE for {year}"))?;
                                    let raw = raw_wape.expect("Raw model precedes candidate");
                                    let bias = relative.expect("Positive S-NPP denominator");
                                    western_years += 1;
                                    western_wins += usize::from(wape < raw);
                                    western_bias_passes += usize::from(bias.abs() <= BIAS_LIMIT);
                                    eprintln!("western_us {year}: raw WAPE {:.2}%, frozen WAPE {:.2}%, bias {:+.2}%",
                                              100.0 * raw, 100.0 * wape, 100.0 * bias);
                                }
                            }
                        }
                    }
                }
            }
        }
        if !fresh {
            let mut selection = csv::Writer::from_path(out.join("selection.csv"))?;
            selection.write_record(["model", "median_monthly_wape", "median_improvement_vs_raw",
                "regions_improved", "regions_abs_bias_le_20pct", "passes_discovery_gate", "selected"])?;
            let mut raw = control[0].map(|c| c.0);
            raw.sort_by(f64::total_cmp);
            let mut rows = Vec::new();
            for (m, &model) in MODELS.iter().enumerate() {
                let mut wapes = control[m].map(|c| c.0);
                wapes.sort_by(f64::total_cmp);
                let wins = control[m].iter().zip(control[0])
                    .filter(|(candidate, raw)| candidate.0 < raw.0).count();
                let biases = control[m].iter().filter(|c| c.1.abs() <= BIAS_LIMIT).count();
                let passes = raw[4] - wapes[4] >= 0.05 && wins >= 6 && biases >= 6;
                rows.push((model, wapes[4], raw[4] - wapes[4], wins, biases, passes));
            }
            chosen = select(std::array::from_fn(|m| rows[m].5.then_some(rows[m].1)));
            for (m, row) in rows.into_iter().enumerate() {
                selection.serialize((row.0, row.1, row.2, row.3, row.4, row.5, chosen == Some(m)))?;
            }
            selection.flush()?;
            if let Some(model) = chosen {
                eprintln!("E18 selected {} for western holdout", MODELS[model]);
            }
        }
    }
    metrics.flush()?;
    factors.flush()?;
    peaks.flush()?;
    monthly.flush()?;
    if freeze {
        let model = chosen.ok_or_else(|| anyhow::anyhow!("No model passed the discovery gate"))?;
        ensure!(western_years == 5 && western_wins > western_years / 2
                && western_bias_passes > western_years / 2, "Western holdout gate failed");
        let (n, counts) = western_support.expect("Western training fold");
        let factor = folds[0][model];
        export(out, model, factor, n, counts, "frozen_e18")?;
        eprintln!("E18 frozen: {}, day {}, night {}; western wins {western_wins}/{western_years}, bias passes {western_bias_passes}/{western_years}",
                  MODELS[model], factor[0], factor[1]);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::select;

    #[test]
    fn close_candidates_prefer_simplicity_after_the_gate() {
        assert_eq!(select([None; 6]), None);
        assert_eq!(select([None, Some(0.236), None, None, Some(0.229), Some(0.231)]), Some(1));
        assert_eq!(select([None, Some(0.250), None, Some(0.235), Some(0.231), Some(0.236)]), Some(5));
        assert_eq!(select([None, Some(0.250), None, Some(0.235), Some(0.230), Some(0.246)]), Some(4));
    }
}

